#!/usr/bin/env python3
"""Shared evidence validation (stdlib only).

Imported by ``scripts/publish_evidence.py`` (main's copy: the privileged
publisher treats the artifact as hostile) and, from part 5, by the ``ci.yml``
evidence job through the ``check`` subcommand (the PR's own copy: it catches
honest mistakes only, because a hostile PR controls that copy).

Layout contract: the artifact root holds ``results.json`` (the structured
scenario results ``pr_evidence.build_results`` writes) and ``ui_out/`` (the
screenshots plus ``ui_manifest.json`` from ``ui_evidence``).
"""

from __future__ import annotations

import argparse
import json
import re
import struct
import sys
import zlib
from pathlib import Path

RESULTS_FILENAME = "results.json"

# The artifact is PR-produced data, so every field has a cap. The comment
# budget (60 KiB) trims far below these; they only bound what the privileged
# publisher is willing to read and parse.
RESULTS_MAX_BYTES = 5_000_000
RESULTS_MAX_SCENARIOS = 256
RESULTS_MAX_TEXT = 1_000_000
RESULTS_MAX_ID_LEN = 64
RESULTS_MAX_TITLE_LEN = 200
RESULTS_MAX_COMMAND_ARGS = 16
RESULTS_MAX_COMMAND_ARG_LEN = 512
RESULTS_MAX_COMMAND_TOTAL = 2048

RESULTS_VERSION = 1
RESULTS_KNOWN_KEYS = frozenset({"version", "metadata", "scenarios", "removed"})
RESULTS_METADATA_KEYS = frozenset({"generator", "head_sha", "base_has_package"})
SCENARIO_KNOWN_KEYS = frozenset(
    {
        "id",
        "title",
        "command",
        "exit_before",
        "exit_after",
        "expected_exit",
        "size_before",
        "size_after",
        "changed",
        "new_in_pr",
        "before",
        "after",
    }
)
# Every field the comment renderer reads directly. ``new_in_pr`` stays
# optional (the renderer only asks for it with a default); a scenario
# missing any other field would raise KeyError mid-render instead of
# refusing with a fixed reason.
SCENARIO_REQUIRED_KEYS = SCENARIO_KNOWN_KEYS - {"new_in_pr"}

ID_RE = re.compile(r"[A-Za-z0-9_.-]+")
SHA_RE = re.compile(r"[0-9a-f]{40}")

# Fixed refusal reasons (Decision 4, option B). When the publisher refuses
# an artifact it posts a notice built only from main's text plus one of
# these codes: no PR-supplied content may reach the comment.
REFUSAL_REASONS = (
    "missing",
    "too_large",
    "bad_png",
    "bad_schema",
    "stale_head",
    "render_error",
    "publish_failed",
)
REFUSAL_SENTENCES = {
    "missing": "the CI artifact was missing or unreadable, so there is nothing to show.",
    "too_large": "the evidence exceeded its size limit, so the whole artifact was refused.",
    "bad_png": "a screenshot failed validation, so the whole artifact was refused.",
    "bad_schema": "the evidence data failed validation, so the whole artifact was refused.",
    "stale_head": (
        "the evidence is not for the PR's current head commit; "
        "a newer run will publish."
    ),
    "render_error": (
        "the evidence data broke the publisher while rendering, "
        "so the whole artifact was refused."
    ),
    "publish_failed": (
        "the publisher could not finish publishing, "
        "so there is no evidence to show."
    ),
}
REFUSAL_MARKER = "<!-- housesitter-evidence -->"


def refusal_notice(reason: str) -> str:
    """Build the fixed refusal notice for a reason code.

    Only main's text plus the code: there are no slots for PR content, so
    a hostile artifact cannot shape this comment. Raises ValueError for an
    unknown reason (a caller bug, never PR data).
    """
    if reason not in REFUSAL_SENTENCES:
        raise ValueError(f"unknown refusal reason: {reason!r}")
    return (
        f"{REFUSAL_MARKER}\n"
        "## Before / after evidence\n"
        "\n"
        f"**Evidence unavailable:** {REFUSAL_SENTENCES[reason]}\n"
        "\n"
        "This notice was generated by main's publisher from fixed text; "
        "it contains no PR-supplied content. "
        f"Reason code: `{reason}`.\n"
    )


def artifact_refusal_reason(errors: list[str]) -> str:
    """Map UI artifact validation errors to a refusal reason.

    Size caps are ``too_large``; PNG structure problems are ``bad_png``;
    everything else (manifest shape, names, missing files) is
    ``bad_schema``. The message fragments below are a contract with
    ``ui_evidence.validate_artifact``: its PNG messages name the format
    ("PNG ...", "not a PNG file"), its cap messages say "over the ... cap".
    """
    for error in errors:
        if "over the" in error and "cap" in error:
            return "too_large"
    for error in errors:
        if "not a PNG file" in error or (
            "PNG" in error
            and any(
                word in error
                for word in (
                    "CRC",
                    "chunk",
                    "IHDR",
                    "IEND",
                    "IDAT",
                    "trailing",
                    "truncated",
                    "dimensions",
                    "decompress",
                    "colour",
                    "color",
                    "bit depth",
                    "interlace",
                )
            )
        ):
            return "bad_png"
    return "bad_schema"


def _is_exit(value: object) -> bool:
    """A real int exit code, or the string "timeout" a hung scenario yields."""
    return type(value) is int and -255 <= value <= 255 or value == "timeout"


def _has_controls(text: str) -> bool:
    return any(ord(char) < 0x20 for char in text)


def _is_encodable(text: str) -> bool:
    """Whether ``text`` encodes as UTF-8 (a lone surrogate encodes nowhere)."""
    try:
        text.encode("utf-8")
    except UnicodeEncodeError:
        return False
    return True


def validate_results(doc: object, known_ids: set[str]) -> list[str]:
    """Check the structured results against the strict schema.

    ``known_ids`` are the scenario ids in MAIN's
    ``tests/evidence/scenarios.json``. An unknown id is accepted only when
    the entry is marked ``new_in_pr`` (a scenario this PR adds). A known id
    is accepted with or without the flag: the builder marks "new" against
    the base tree, which can be older than main. Returns a list of errors;
    empty means valid.
    """
    errors: list[str] = []
    if not isinstance(doc, dict):
        return ["results must be an object"]
    unknown = set(doc) - RESULTS_KNOWN_KEYS
    if unknown:
        errors.append(f"unknown top-level keys: {sorted(unknown)}")
    if doc.get("version") != RESULTS_VERSION:
        errors.append(f"version must be {RESULTS_VERSION}")
    metadata = doc.get("metadata", {})
    if not isinstance(metadata, dict):
        errors.append("metadata must be an object")
    else:
        unknown_meta = set(metadata) - RESULTS_METADATA_KEYS
        if unknown_meta:
            errors.append(f"unknown metadata keys: {sorted(unknown_meta)}")
        generator = metadata.get("generator", "")
        if not isinstance(generator, str) or len(generator) > 128:
            errors.append("metadata.generator must be a short string")
        head_sha = metadata.get("head_sha")
        if head_sha is not None and (
            not isinstance(head_sha, str) or not SHA_RE.fullmatch(head_sha)
        ):
            errors.append("metadata.head_sha must be a 40-hex SHA or absent")
        base_has_package = metadata.get("base_has_package", True)
        if type(base_has_package) is not bool:
            errors.append("metadata.base_has_package must be a bool")
    removed = doc.get("removed", [])
    if not isinstance(removed, list) or any(
        not isinstance(item, str) or item not in known_ids for item in removed
    ):
        shown = sorted(str(item)[:80] for item in removed)[:10] if isinstance(
            removed, list
        ) else removed
        errors.append(f"removed must be a list of known scenario ids, got: {shown}")
    scenarios = doc.get("scenarios")
    if not isinstance(scenarios, list):
        errors.append("scenarios must be a list")
        return errors
    if len(scenarios) > RESULTS_MAX_SCENARIOS:
        errors.append(
            f"scenarios lists {len(scenarios)} entries, "
            f"over the {RESULTS_MAX_SCENARIOS} cap"
        )
    seen: set[str] = set()
    for index, entry in enumerate(scenarios):
        where = f"scenarios[{index}]"
        if not isinstance(entry, dict):
            errors.append(f"{where} must be an object")
            continue
        unknown_keys = set(entry) - SCENARIO_KNOWN_KEYS
        if unknown_keys:
            errors.append(f"{where} has unknown keys: {sorted(unknown_keys)}")
        missing = SCENARIO_REQUIRED_KEYS - set(entry)
        if missing:
            errors.append(f"{where} is missing keys: {sorted(missing)}")
            continue

        ident = entry.get("id")
        if (
            not isinstance(ident, str)
            or not 1 <= len(ident) <= RESULTS_MAX_ID_LEN
            or not ID_RE.fullmatch(ident)
        ):
            errors.append(f"{where}.id must match {ID_RE.pattern}, got: {str(ident)[:80]}")
            continue
        if not _is_encodable(ident):
            errors.append(f"{where}.id must be encodable as UTF-8")
        if ident in seen:
            errors.append(f"duplicate scenario id: {ident}")
        seen.add(ident)
        if ident not in known_ids and entry.get("new_in_pr") is not True:
            errors.append(f"unknown scenario id without new_in_pr: {ident}")
        title = entry.get("title", "")
        if (
            not isinstance(title, str)
            or len(title) > RESULTS_MAX_TITLE_LEN
            or _has_controls(title)
        ):
            errors.append(f"{where}.title must be a short single-line string")
        if isinstance(title, str) and not _is_encodable(title):
            errors.append(f"{where}.title must be encodable as UTF-8")
        command = entry.get("command")
        if (
            not isinstance(command, list)
            or not 1 <= len(command) <= RESULTS_MAX_COMMAND_ARGS
            or any(
                not isinstance(arg, str)
                or not 1 <= len(arg) <= RESULTS_MAX_COMMAND_ARG_LEN
                or "\x00" in arg
                for arg in command
            )
            or sum(len(arg) for arg in command) > RESULTS_MAX_COMMAND_TOTAL
        ):
            errors.append(f"{where}.command must be a short list of short strings")
        if isinstance(command, list):
            for arg in command:
                if isinstance(arg, str) and not _is_encodable(arg):
                    errors.append(f"{where}.command must be encodable as UTF-8")
                    break
        if not _is_exit(entry.get("exit_before")) and entry.get("exit_before") is not None:
            errors.append(f"{where}.exit_before must be an exit code, timeout, or null")
        if not _is_exit(entry.get("exit_after")):
            errors.append(f"{where}.exit_after must be an exit code or timeout")
        expected = entry.get("expected_exit")
        if type(expected) is not int or not 0 <= expected <= 255:
            errors.append(f"{where}.expected_exit must be an exit code")
        for side in ("size_before", "size_after"):
            value = entry.get(side)
            if value is not None and (
                type(value) is not int or not 0 <= value <= 10_000_000
            ):
                errors.append(f"{where}.{side} must be a byte size or null")
        if type(entry.get("changed")) is not bool:
            errors.append(f"{where}.changed must be a bool")
        if "new_in_pr" in entry and type(entry["new_in_pr"]) is not bool:
            errors.append(f"{where}.new_in_pr must be a bool")
        before = entry.get("before")
        if before is not None and (
            not isinstance(before, str) or len(before) > RESULTS_MAX_TEXT
        ):
            errors.append(f"{where}.before must be a capped string or null")
        if isinstance(before, str) and not _is_encodable(before):
            errors.append(f"{where}.before must be encodable as UTF-8")
        after = entry.get("after")
        if not isinstance(after, str) or len(after) > RESULTS_MAX_TEXT:
            errors.append(f"{where}.after must be a capped string")
        if isinstance(after, str) and not _is_encodable(after):
            errors.append(f"{where}.after must be encodable as UTF-8")
    return errors


def load_known_scenario_ids(scenarios_path: Path) -> set[str]:
    """Read the scenario ids from a ``tests/evidence/scenarios.json`` file."""
    data = json.loads(scenarios_path.read_text(encoding="utf-8"))
    return {entry["id"] for entry in data["scenarios"]}


# PNG structure validation (S5) -------------------------------------------------
#
# The old check looked at 8 magic bytes only. This parses the structure:
# chunk lengths within the file, CRC of every chunk, IHDR first with sane
# dimensions, an allow-list of colour types, IEND last with no trailing
# bytes, and a bounded decompression of IDAT. Stdlib only.

PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
# Sane dimension caps. Height matches ui_evidence.MAX_PAGE_HEIGHT_PX (pinned
# by test): captures are viewport-wide and page-cropped, so anything bigger
# is either hostile or broken. Width has no capture-side cap; 4096 (4K)
# leaves wide headroom over the 1280 CSS px viewports. The pixel cap keeps
# the bounded decompression below ~64 MiB of output.
PNG_MAX_WIDTH = 4096
PNG_MAX_HEIGHT = 120_000
PNG_MAX_PIXELS = 16_777_216
PNG_CHANNELS = {2: 3, 6: 4}  # 8-bit RGB/RGBA non-interlaced: what the pipeline emits
# Chunk types the pipeline's screenshots contain. A real Chromium capture
# holds IHDR, IDAT and IEND only (pinned by test): the pipeline emits
# 8-bit RGB/RGBA, which never uses a palette, so PLTE (and colour type 3,
# refused with the other non-RGB/RGBA types below) is refused entirely —
# either hostile bytes or a sign the capture pipeline changed, and both
# fail closed. Everything else — text chunks, timestamps, colour
# profiles, and animation chunks (acTL/fcTL/fdAT) — is refused the same
# way. IDAT chunks must also be consecutive: anything interleaved between
# them is refused even if its type were ever allow-listed.
PNG_ALLOWED_CHUNKS = frozenset({b"IHDR", b"IDAT", b"IEND"})


def _chunk_name(ctype: bytes) -> str:
    try:
        return ctype.decode("ascii")
    except ValueError:
        return repr(ctype)


def validate_png(data: bytes) -> list[str]:
    """Validate PNG structure. Returns a list of errors; empty means valid."""
    if data[:8] != PNG_MAGIC:
        return ["not a PNG file"]
    pos = 8
    width = height = channels = None
    idat = bytearray()
    seen_idat = False
    while pos + 8 <= len(data):
        (length,) = struct.unpack(">I", data[pos : pos + 4])
        ctype = data[pos + 4 : pos + 8]
        end = pos + 12 + length
        if end > len(data):
            return ["truncated PNG chunk"]
        body = data[pos + 8 : end - 4]
        (stored_crc,) = struct.unpack(">I", data[end - 4 : end])
        if zlib.crc32(data[pos + 4 : end - 4]) & 0xFFFFFFFF != stored_crc:
            return [f"PNG CRC mismatch in {_chunk_name(ctype)} chunk"]
        if width is None:
            if ctype != b"IHDR" or length != 13:
                return ["PNG's first chunk must be a 13-byte IHDR"]
        if not all(0x41 <= byte <= 0x5A or 0x61 <= byte <= 0x7A for byte in ctype):
            return [f"PNG chunk has a non-letter type name: {_chunk_name(ctype)}"]
        if ctype not in PNG_ALLOWED_CHUNKS:
            return [f"PNG has an unexpected {_chunk_name(ctype)} chunk"]
        if width is None:
            (width, height, bit_depth, color_type, comp, filt, interlace) = (
                struct.unpack(">IIBBBBB", body)
            )
            if width < 1 or height < 1:
                return ["PNG dimensions must be positive"]
            if width > PNG_MAX_WIDTH or height > PNG_MAX_HEIGHT:
                return [
                    f"PNG dimensions {width}x{height} exceed "
                    f"{PNG_MAX_WIDTH}x{PNG_MAX_HEIGHT}"
                ]
            if width * height > PNG_MAX_PIXELS:
                return [f"PNG claims {width * height} pixels, over the cap"]
            if bit_depth != 8 or color_type not in PNG_CHANNELS or interlace != 0:
                return [
                    "PNG must be 8-bit RGB/RGBA non-interlaced "
                    f"(bit depth {bit_depth}, colour type {color_type}, "
                    f"interlace {interlace})"
                ]
            if comp != 0 or filt != 0:
                return ["PNG uses an unknown compression or filter method"]
            channels = PNG_CHANNELS[color_type]
        elif ctype == b"IHDR":
            return ["PNG has more than one IHDR"]
        elif ctype == b"IDAT":
            seen_idat = True
            idat += body
        elif seen_idat and ctype != b"IEND":
            return [
                "PNG IDAT chunks must be consecutive: "
                f"{_chunk_name(ctype)} chunk after IDAT image data"
            ]
        elif ctype == b"IEND":
            if length != 0:
                return ["PNG IEND chunk must be empty"]
            if end != len(data):
                return ["PNG has trailing bytes after IEND"]
            break
        pos = end
    else:
        return ["PNG ends without IEND"]
    if not seen_idat:
        return ["PNG has no IDAT image data"]
    # The IDAT stream must decode to exactly the IHDR size: height rows of
    # one filter byte plus width pixels. Interlaced images are rejected
    # above, so no interlace pass math is needed. The output cap is the
    # exact size, so memory stays bounded; then the stream must end cleanly
    # (a truncated stream or garbage after it refuses) and every scanline's
    # filter byte must be a defined type (0-4).
    expected = height * (1 + width * channels)
    try:
        decoder = zlib.decompressobj()
        out = decoder.decompress(bytes(idat), expected)
    except zlib.error as exc:
        return [f"PNG image data does not decompress: {exc}"]
    if not decoder.eof:
        return ["PNG image data is truncated: the zlib stream ends early"]
    if decoder.unused_data or decoder.unconsumed_tail:
        return ["PNG image data has trailing bytes after the zlib stream"]
    if len(out) != expected:
        return [
            f"PNG image data decodes to {len(out)} bytes, "
            f"expected {expected} from IHDR"
        ]
    if decoder.flush() != b"":
        return ["PNG image data has trailing bytes after the zlib stream"]
    stride = 1 + width * channels
    for row in range(height):
        if out[row * stride] > 4:
            return [f"PNG scanline {row} has an invalid filter byte (IDAT image data)"]
    return []


def cmd_check(args) -> int:
    """Run the publisher's refusal decision over an artifact directory.

    Used by the ``ci.yml`` evidence job on its own just-built artifact, so
    an honest mistake fails the job (red ``ci-ok``) before upload. This
    runs the PR's own copy of every script, so it catches honest mistakes
    only; the publisher's notice (main's code) covers hostile artifacts.
    Exit codes mirror the publisher: 0 the publisher would publish, 1 it
    would refuse (the reason prints to stdout), 2 bad caller arguments.
    """
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import publish_evidence  # noqa: E402  (same copy: the PR's, or main's)

    try:
        publish_evidence.render_comment(
            Path(args.artifact_dir), args.repo, args.pr, args.head_sha
        )
    except publish_evidence.PublishError as exc:
        # The message goes to the job log (PR-visible anyway) so an honest
        # mistake is debuggable; only the fixed reason reaches the comment.
        print(f"evidence_checks: publisher would refuse: {exc.reason}: {exc}")
        return 1
    except ValueError as exc:
        print(f"evidence_checks: bad argument: {exc}", file=sys.stderr)
        return 2
    print("evidence_checks: publisher would publish")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    check = sub.add_parser(
        "check", help="run the publisher's refusal decision over an artifact"
    )
    check.add_argument("--artifact-dir", required=True)
    check.add_argument("--repo", required=True)
    check.add_argument("--pr", required=True, type=int)
    check.add_argument("--head-sha", required=True)
    check.set_defaults(func=cmd_check)
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except ValueError as exc:
        print(f"evidence_checks: bad argument: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
